//! Giallo-backed, class-only fenced-code rendering.

use giallo::{HighlightOptions, HtmlRenderer, Registry, RenderOptions, ThemeVariant};

use crate::config::{HighlightingConfig, MissingLanguage};

const CLASS_PREFIX: &str = "heine-";
const BLOCK_CSS: &str = ".giallo > code { background: transparent; }\n";

pub(super) struct Highlighter {
    registry: Registry,
    light_theme: String,
    dark_theme: String,
    missing_language: MissingLanguage,
    stylesheet: String,
}

impl Highlighter {
    pub(super) fn new(config: &HighlightingConfig) -> Result<Self, giallo::Error> {
        let mut registry = Registry::builtin()?;
        registry.link_grammars();
        let (light, dark) =
            registry.generate_dual_css(config.light_theme(), config.dark_theme(), CLASS_PREFIX)?;
        let stylesheet = format!(
            "/* Generated by Heine. Load an authored stylesheet afterwards to override it. */\n{BLOCK_CSS}{light}\n@media (prefers-color-scheme: dark) {{\n{dark}\n}}\n"
        );
        Ok(Self {
            registry,
            light_theme: config.light_theme().into(),
            dark_theme: config.dark_theme().into(),
            missing_language: config.missing_language(),
            stylesheet,
        })
    }

    pub(super) fn stylesheet(&self) -> String {
        self.stylesheet.clone()
    }

    pub(super) fn render(&self, language: &str, source: &str) -> Result<String, giallo::Error> {
        let options = HighlightOptions::new(
            language,
            ThemeVariant::Dual {
                light: &self.light_theme,
                dark: &self.dark_theme,
            },
        )
        .fallback_to_plain(self.missing_language == MissingLanguage::Plain);
        let highlighted = self.registry.highlight(source, &options)?;
        Ok(HtmlRenderer {
            css_class_prefix: Some(CLASS_PREFIX.into()),
            ..HtmlRenderer::default()
        }
        .render(&highlighted, &RenderOptions::default()))
    }

    /// Resolve the fence language without constructing highlighted HTML during
    /// the source-validation pass. Rendering still highlights the complete
    /// block later when a template selects the Markdown input.
    pub(super) fn validate(&self, language: &str) -> Result<(), giallo::Error> {
        let options = HighlightOptions::new(
            language,
            ThemeVariant::Dual {
                light: &self.light_theme,
                dark: &self.dark_theme,
            },
        )
        .fallback_to_plain(self.missing_language == MissingLanguage::Plain);
        self.registry.highlight("", &options).map(|_| ())
    }
}
