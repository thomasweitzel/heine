//! Opt-in checks against locally installed external renderer programs.

use std::{fs, process::Command};

use heine::{BuildMode, BuildOptions, build_at_with_options};

mod support;

use support::Fixture;

fn require_program(program: &str) {
    let status = Command::new(program)
        .arg("--version")
        .status()
        .unwrap_or_else(|error| panic!("could not start required {program} test program: {error}"));
    assert!(
        status.success(),
        "required {program} test program did not succeed"
    );
}

fn build_with_renderers(fixture: &Fixture) {
    build_at_with_options(
        fixture.path(),
        BuildOptions::new(BuildMode::Full)
            .allow_external_renderers()
            .refresh_renderers(),
    )
    .expect("external renderer fixture builds");
}

#[test]
#[ignore = "requires the locally installed pandoc and typst programs"]
fn pandoc_and_typst_profiles_produce_checked_replacements_and_resources() {
    require_program("pandoc");
    require_program("typst");
    let fixture = Fixture::new();
    fixture.write(
        "heine.toml",
        r#"
[renderers.pandoc]
protocol = "stream"
program = "pandoc"
timeout_seconds = 30
cache_identity = "pandoc-integration"
inputs = ["body"]
result = "html"

[renderers.pandoc.block]
arguments = ["--from", "markdown", "--to", "html"]

[renderers.typst_pdf]
protocol = "workspace"
program = "typst"
timeout_seconds = 30
cache_identity = "typst-integration"
inputs = ["body"]
input_extension = "typ"
result = "link"
media_type = "application/pdf"
extension = "pdf"

[renderers.typst_pdf.block]
arguments = ["compile", "{input_file}", "{output_file}", "--format", "pdf"]

[renderers.typst_svg]
protocol = "workspace"
program = "typst"
timeout_seconds = 30
cache_identity = "typst-integration"
inputs = ["body"]
input_extension = "typ"
result = "svg"
materializations = ["resource"]

[renderers.typst_svg.block]
arguments = ["compile", "{input_file}", "{output_file}", "--format", "svg"]

[renderers.typst_png]
protocol = "workspace"
program = "typst"
timeout_seconds = 30
cache_identity = "typst-integration"
inputs = ["body"]
input_extension = "typ"
result = "image"
media_type = "image/png"
extension = "png"

[renderers.typst_png.block]
arguments = ["compile", "{input_file}", "{output_file}", "--format", "png"]

[renderers.typst_picture]
protocol = "workspace"
program = "typst"
timeout_seconds = 30
cache_identity = "typst-integration"
inputs = ["body"]
input_extension = "typ"
result = "picture"
media_type = "image/svg+xml"
extension = "svg"

[renderers.typst_picture.block.light]
arguments = ["compile", "{input_file}", "{output_file}", "--format", "svg", "--input", "scheme=light"]

[renderers.typst_picture.block.dark]
arguments = ["compile", "{input_file}", "{output_file}", "--format", "svg", "--input", "scheme=dark"]
"#,
    );
    fixture.write(
        "templates/page.tera",
        "<!doctype html><html><body>{{ markdown(content='main') }}</body></html>",
    );
    fixture.write(
        "content/en/index.page",
        "title = 'External renderer integration'\ntemplate = 'page.tera'\ncontent.main = 'index.md'\n",
    );
    fixture.write(
        "content/en/index.md",
        r#"
:::render[pandoc]
## Rendered by Pandoc

A *checked* HTML replacement.
:::

:::render[typst_pdf label="Download the report"]
= Report

Generated by Typst.
:::

:::render[typst_svg alt="A blue Typst rectangle"]
#rect(width: 20pt, height: 10pt, fill: blue)
:::

:::render[typst_png alt="A green Typst rectangle"]
#rect(width: 20pt, height: 10pt, fill: green)
:::

:::render[typst_picture alt="A scheme-aware Typst rectangle" class="diagram"]
#rect(width: 20pt, height: 10pt, fill: if sys.inputs.at("scheme") == "dark" { white } else { black })
:::
"#,
    );

    build_with_renderers(&fixture);

    let html = fs::read_to_string(fixture.path().join("public/index.html")).expect("rendered page");
    assert!(html.contains("<h2"), "{html}");
    assert!(html.contains("Rendered by Pandoc"));
    assert!(html.contains("heine-renderers/sha256-"), "{html}");
    assert!(html.contains(">Download the report</a>"));
    assert_eq!(html.matches("<img").count(), 3, "{html}");
    assert!(html.contains("<picture class=\"diagram\">"), "{html}");

    let resources = fs::read_dir(fixture.path().join("public/heine-renderers"))
        .expect("renderer resources")
        .map(|entry| entry.expect("renderer resource").path())
        .collect::<Vec<_>>();
    assert_eq!(resources.len(), 5);
    assert!(resources.iter().any(|path| {
        path.extension().is_some_and(|extension| extension == "pdf")
            && fs::read(path).expect("PDF resource").starts_with(b"%PDF-")
    }));
    assert!(resources.iter().any(|path| {
        path.extension().is_some_and(|extension| extension == "svg")
            && fs::read_to_string(path)
                .expect("SVG resource")
                .contains("<svg")
    }));
    assert!(resources.iter().any(|path| {
        path.extension().is_some_and(|extension| extension == "png")
            && fs::read(path)
                .expect("PNG resource")
                .starts_with(b"\x89PNG\r\n\x1a\n")
    }));
}
